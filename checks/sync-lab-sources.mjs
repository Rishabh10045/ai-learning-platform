// node checks/sync-lab-sources.mjs [--check] : embeds every file a main-topic lab shows (Java program, SQL schema,
// helpers, scenario and its expected output) into main-labs-code.js, so the static site renders the exact files
// that CI runs. --check exits 1 when main-labs-code.js is out of date (used by checks/main-labs.test.mjs).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { mainLabs } from '../main-labs.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export function labSourcePaths() {
  const paths = new Set(['booking/sql/schema.sql', 'booking/sql/helpers.sql']);
  for (const lab of Object.values(mainLabs)) {
    paths.add(lab.file);
    for (const f of lab.sql || []) { paths.add(f); paths.add('booking/sql/expected/' + f.split('/').pop().replace(/\.sql$/, '.out')); }
  }
  return [...paths].sort();
}
export function render() {
  const files = Object.fromEntries(labSourcePaths().map(p => [p, existsSync(join(root, p)) ? readFileSync(join(root, p), 'utf8') : null]));
  return '// GENERATED by checks/sync-lab-sources.mjs from the files named below. Do not edit by hand; edit the file and re-run.\n'
    + 'export const labFiles = ' + JSON.stringify(files, null, 1) + ';\n';
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = join(root, 'main-labs-code.js'), next = render();
  if (process.argv.includes('--check')) {
    const same = existsSync(out) && readFileSync(out, 'utf8') === next;
    console.log(same ? 'main-labs-code.js is up to date' : 'main-labs-code.js is OUT OF DATE: run node checks/sync-lab-sources.mjs');
    process.exit(same ? 0 : 1);
  }
  writeFileSync(out, next);
  console.log('wrote main-labs-code.js (' + labSourcePaths().length + ' files)');
}
