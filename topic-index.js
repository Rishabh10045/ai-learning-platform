const subjectByPrefix = {
  j: 'Java', b: 'Spring Boot & backend', l: 'Low-level design', h: 'System design', d: 'DSA in Java', ai: 'AI engineering'
};

export const topicIndex = days.flatMap(day => day.topics.filter(id => !id.startsWith('LAB-')).map(code => {
  const id = code.toLowerCase();
  const subject = /^b-(sql|jdbc|schema|transactions)-/.test(id) ? 'SQL and data' : subjectByPrefix[id.split('-')[0]];
  return { id, title: titles[id], subject, day: day.number, lessonId: day.topics[0].toLowerCase() };
}));

const byId = new Map(topicIndex.map(topic => [topic.id, topic]));
export const getTopic = id => byId.get(id);
